"""BIL-C: billing-grade cost accounting in the call register.

Revision ID: esc_billing_grade_cost
Revises: submission_awaiting_criteria
Create Date: 2026-10-29

The call register is the source of every money figure the platform reads (the
stage sum the funds port is told, the cost reports, margin telemetry), so each
row of a paid call now carries a sum that can be checked by arithmetic on the
row alone:

* ``cost_usd`` and ``ceiling_estimate_usd`` become ``NUMERIC(18,12)`` (decision
  4: money is never a float);
* ``cost_kind`` — exact / estimated / unknown (decision 2), CHECK-bound;
* ``unit_in_cached`` — the provider's count of input served from its cache;
* ``unit_in_estimate`` / ``unit_out_estimate`` — our own token counts, the
  first on every LLM attempt without attachments (it stands in for a missing
  provider count and, beside a reported one, measures our count's error);
* ``catalog_version``, ``tariff_window``, ``call_started_at`` and the four
  applied unit prices — which prices the row was computed from (decision 1).

Six CHECKs keep the rows honest (vocabularies spelled out literally — a
migration must not change meaning when the code later does):

* ``ck_esc_cost_kind`` / ``ck_esc_tariff_window`` — the vocabularies;
* ``ck_esc_cost_kind_amount`` — a sum exactly when the kind has one;
* ``ck_esc_priced_call`` — a row that counts units names the kind of its sum;
* ``ck_esc_exact_is_priced`` — an exact row names its catalog version and
  tariff window;
* ``ck_esc_cached_within_input`` — cached input is part of the input.

Back-fill (decision P8):

* rows written before this migration with a sum become ``estimated`` (the sum
  ignored cached tokens and the time of day, and no unit prices were kept);
* rows of a call without a sum become ``unknown`` — a row that counts units,
  or a row of a call (``success`` set, a provider named) that is not a webhook
  delivery (``provider = 'httpx'``); this catches the speech-to-text failures
  written with ``provider = 'unknown'`` and no unit type;
* every other row (ladder traces, metrics, funds-port, webhook rows) keeps no
  kind; ``catalog_version`` and the prices stay NULL on all old rows;
* ``jobs.course_node_id`` of the key-explanation jobs is filled from their
  task's ``authored_documents.course_node_id`` (decision 5) — except on
  soft-deleted jobs, which the soft-delete trigger keeps unchanged.

Hand-written, not autogenerated (``DD-L4-A``): the ESC table's other comment
drift is not touched. The one existing comment changed is ``unit_out_reasoning``
(the OpenAI-compatible connectors now read DeepSeek's reasoning count); the
replaced text was read from the development database before writing this file.

Downgrade drops the new columns and CHECKs, restores the float types and the
old comment. The key-explanation attribution is not undone: it is correct, and
the rows it filled cannot be told from the rows written that way since.
"""

