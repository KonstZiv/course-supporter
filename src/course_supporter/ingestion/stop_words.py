def build_stop_words(
    *,
    natural_lang: str = "en",
    programming_lang: str = "python",
) -> frozenset[str]:
    """Build a combined stop word set for the given languages.

    Args:
        natural_lang: ISO 639-1 code (en, uk, de, sr, hr, cnr, es, tr,
            ro, bg, pl, lt, sv, fr). Defaults to English.
        programming_lang: Language name (python, javascript, typescript,
            csharp, java, sql, rust, go, css, html, elixir, c, cpp).
            Defaults to Python.

    Returns:
        Combined frozenset of stop words from both sources.
        Unknown languages are silently ignored (empty contribution).
    """
    nat = _NATURAL_LANGUAGES.get(natural_lang, frozenset())
    prog = _PROGRAMMING_LANGUAGES.get(programming_lang, frozenset())
    return nat | prog


def supported_natural_languages() -> list[str]:
    """Return list of supported natural language codes."""
    return list(_NATURAL_LANGUAGES.keys())


def supported_programming_languages() -> list[str]:
    """Return list of supported programming language names."""
    return list(_PROGRAMMING_LANGUAGES.keys())
