# ── Parent resolution (two-hop CourseNode lookup) ────────────────


class TestFetchParentRaw:
    """``_fetch_parent_raw`` walks CourseNode → parent_id → parent Raw.

    Drives the real resolver against an ``AsyncMock`` session that
    returns a synthetic ``CourseNode`` (for ``session.get``) and a
    synthetic parent Raw (for the ``select`` query result).
    """

    async def test_root_returns_none(self) -> None:
        # CourseNode with parent_id IS NULL → no parent Raw.
        from course_supporter.storage.orm import CourseNode

        course_node = CourseNode(
            id=uuid.uuid4(),
            tenant_id=uuid.uuid4(),
            parent_id=None,
            title="root",
            default_language="ukr",
        )
        session = AsyncMock()
        session.get.return_value = course_node
        svc = EnclosingContextHashService(session=session)
        child = _make_raw(course_node_id=course_node.id)
        result = await svc._fetch_parent_raw(child)
        assert result is None
        # No SELECT issued — short-circuited at parent_id IS NULL.
        session.execute.assert_not_called()

    async def test_non_root_returns_parent_raw(self) -> None:
        from unittest.mock import MagicMock

        from course_supporter.storage.orm import CourseNode

        parent_node_id = uuid.uuid4()
        course_node = CourseNode(
            id=uuid.uuid4(),
            tenant_id=uuid.uuid4(),
            parent_id=parent_node_id,
            title="child node",
        )
        parent_raw = _make_raw(
            course_node_id=parent_node_id,
            enclosing_context="parent ctx",
        )
        session = AsyncMock()
        session.get.return_value = course_node
        # ``select(...).scalar_one_or_none()`` returns the parent Raw.
        result_mock = MagicMock()
        result_mock.scalar_one_or_none.return_value = parent_raw
        session.execute.return_value = result_mock
        svc = EnclosingContextHashService(session=session)
        child = _make_raw(course_node_id=course_node.id)
        result = await svc._fetch_parent_raw(child)
        assert result is parent_raw

    async def test_missing_course_node_returns_none(self) -> None:
        # Invariant-violation: CourseNode for the node does not exist
        # (orchestrator out-of-order'd or data drift). Service returns
        # None rather than raising — downstream policy decides.
        session = AsyncMock()
        session.get.return_value = None
        svc = EnclosingContextHashService(session=session)
        child = _make_raw()
        result = await svc._fetch_parent_raw(child)
        assert result is None

    async def test_parent_course_node_exists_but_parent_raw_missing(
        self,
    ) -> None:
        # Edge case: parent CourseNode exists but its NodeSummaryRaw
        # hasn't been generated yet (orchestrator out-of-order'd —
        # walked children before parent). Returns None rather than
        # raising; orchestrator-side policy.
        from unittest.mock import MagicMock

        from course_supporter.storage.orm import CourseNode

        course_node = CourseNode(
            id=uuid.uuid4(),
            tenant_id=uuid.uuid4(),
            parent_id=uuid.uuid4(),
            title="child node",
        )
        session = AsyncMock()
        session.get.return_value = course_node
        result_mock = MagicMock()
        result_mock.scalar_one_or_none.return_value = None
        session.execute.return_value = result_mock
        svc = EnclosingContextHashService(session=session)
        child = _make_raw(course_node_id=course_node.id)
        result = await svc._fetch_parent_raw(child)
        assert result is None


# ── Bearing invariant (vision.md:1019) ───────────────────────────


class TestBearingInvariant:
    """vision.md:1019 — the second-axis key is correct ONLY because the
    bottom-up cache holds ``part1`` (NodeSummaryRaw canonical fields)
    byte-stable while ``CourseNode.content_hash`` is stable. Without
    that, LLM non-determinism would drift ``enclosing_context`` from
    re-run to re-run and child source_hashes would never match.

    Without a real LLM in scope, we close this synthetically: a stable
    ``parent.enclosing_context`` MUST produce a byte-stable source_hash
    across an arbitrary number of recomputations. This locks the
    contract that the first-axis cache is what enables the test to
    even be possible in production.
    """

    @pytest.mark.parametrize("recompute_count", [2, 5, 25])
    async def test_stable_parent_context_yields_stable_source_hash(
        self, recompute_count: int
    ) -> None:
        parent = _make_raw(enclosing_context="immutable methodist context")
        child = _make_raw()
        svc = _StubService(parent_raw=parent)
        first = await svc.compute_source_hash_for(child)
        for _ in range(recompute_count):
            assert await svc.compute_source_hash_for(child) == first
