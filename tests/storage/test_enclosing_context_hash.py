# ── Axis independence (acceptance #4) ────────────────────────────


class TestAxisIndependence:
    """The second axis depends ONLY on ``parent.enclosing_context`` —
    never on the node's own ``content_hash`` or own content fields.
    Acceptance #4 — the structural separation between bottom-up (first
    axis) and top-down (second axis).
    """

    async def test_own_content_hash_change_does_not_flip_source_hash(
        self,
    ) -> None:
        parent = _make_raw(enclosing_context="stable parent context")
        # Same parent (== same source_hash input); two children whose
        # only difference is their own content_hash. The second-axis
        # key MUST be identical — the first axis owns content changes.
        child_a = _make_raw()
        child_a.content_hash = "a" * 64
        child_b = _make_raw()
        child_b.content_hash = "b" * 64
        svc = _StubService(parent_raw=parent)
        a_hash = await svc.compute_source_hash_for(child_a)
        b_hash = await svc.compute_source_hash_for(child_b)
        assert a_hash == b_hash

    async def test_own_content_field_change_does_not_flip_source_hash(
        self,
    ) -> None:
        parent = _make_raw(enclosing_context="stable parent context")
        # Same parent; children whose own content fields differ (title,
        # main_concepts, etc.) — first-axis hash would diverge, second
        # axis must NOT.
        child_a = _make_raw(title="Lesson one", main_concepts=["loops"])
        child_b = _make_raw(title="Lesson two", main_concepts=["recursion"])
        svc = _StubService(parent_raw=parent)
        a_hash = await svc.compute_source_hash_for(child_a)
        b_hash = await svc.compute_source_hash_for(child_b)
        assert a_hash == b_hash


# ── is_stale (acceptance #5) ─────────────────────────────────────


class TestIsStale:
    """``is_stale`` is the per-node short-circuit primitive. Acceptance #5."""

    async def test_match_returns_false(self) -> None:
        parent = _make_raw(enclosing_context="parent context")
        child = _make_raw()
        svc = _StubService(parent_raw=parent)
        # Pre-populate child's stored hash with the value that would be
        # computed right now — i.e. an already-up-to-date node.
        child.enclosing_context_source_hash = await svc.compute_source_hash_for(child)
        assert await svc.is_stale(child) is False

    async def test_mismatch_returns_true(self) -> None:
        parent = _make_raw(enclosing_context="parent context")
        child = _make_raw(enclosing_context_source_hash="some-old-stored-hash")
        svc = _StubService(parent_raw=parent)
        assert await svc.is_stale(child) is True

    async def test_root_stable_absence_is_not_stale(self) -> None:
        # Stable-absence case: root (parent_raw=None) + stored is None
        # → not stale. The orchestrator should NOT keep retrying root.
        child = _make_raw(enclosing_context_source_hash=None)
        svc = _StubService(parent_raw=None)
        assert await svc.is_stale(child) is False

    async def test_root_with_lingering_stored_hash_is_stale(self) -> None:
        # If a root somehow has a stored source_hash (e.g. node was
        # demoted from non-root to root) — staleness reports True so
        # the orchestrator can clear it.
        child = _make_raw(enclosing_context_source_hash="stale-from-prior-life")
        svc = _StubService(parent_raw=None)
        assert await svc.is_stale(child) is True


