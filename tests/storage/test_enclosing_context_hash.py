"""Second-axis hash service tests (Phase 3.2.1).

Pins acceptance #3-#5 of task 3.2.1 + the load-bearing invariant from
vision.md:1019:

- #3 — ``compute_source_hash_for`` deterministic; ``parent.enclosing_context``
  change flips the key; stability preserves it.
- #4 — axis independence: a change to the **node's own** ``content_hash``
  (or any other own content field) with stable ``parent.enclosing_context``
  must NOT change ``enclosing_context_source_hash``.
- #5 — short-circuit: ``is_stale`` returns ``False`` when stored equals
  computed, ``True`` otherwise; ``None == None`` is the legitimate
  "stable-absence" case (root or non-root child whose parent has no
  enclosing_context yet).
- Bearing invariant (vision.md:1019) — stable ``parent.enclosing_context``
  ⇒ byte-stable ``source_hash`` regardless of how many times we recompute.

Mirror-sibling shape of ``test_node_summary_formulas.py`` (Phase 3.1):
AsyncMock session, ``_make_raw`` builder with sane defaults, focused
per-property classes. ``_StubService`` overrides ``_fetch_parent_raw``
to bypass the DB lookup — the lookup itself is covered separately so
the formula / staleness tests do not couple to query mocking shape.
"""

from __future__ import annotations

import uuid
from typing import Any
from unittest.mock import AsyncMock

import pytest

from course_supporter.storage.enclosing_context_hash import (
    EnclosingContextHashService,
)
from course_supporter.storage.orm import NodeSummaryRaw


def _make_raw(**overrides: Any) -> NodeSummaryRaw:
    """Build a NodeSummaryRaw with sane defaults; override individual fields.

    Mirrors ``_make_raw`` in ``test_node_summary_formulas.py`` for
    consistency across the storage test suite.
    """
    defaults: dict[str, Any] = {
        "id": uuid.uuid4(),
        "course_node_id": uuid.uuid4(),
        "title": "Node Title",
        "description": "Node description",
        "learning_objectives": [],
        "knowledge": [],
        "skills": [],
        "success_criteria": [],
        "assessment_approach": "",
        "teaching_approach": "",
        "key_activities": [],
        "common_mistakes": [],
        "main_concepts": [],
        "secondary_concepts": [],
        "compressed_summary": "",
        "enclosing_context": None,
        "methodist_observations": [],
        "own_documents_count": 0,
        "own_chars_count": 0,
        "cumulative_documents_count": 0,
        "cumulative_chars_count": 0,
        "enclosing_context_source_hash": None,
    }
    defaults.update(overrides)
    raw = NodeSummaryRaw(**defaults)
    raw.deleted_at = None
    return raw


class _StubService(EnclosingContextHashService):
    """``EnclosingContextHashService`` with the DB-side parent resolver
    stubbed out.

    Allows formula / staleness tests to control the resolved parent
    directly. The real ``_fetch_parent_raw`` is covered by its own
    test class.
    """

    def __init__(self, parent_raw: NodeSummaryRaw | None) -> None:
        super().__init__(session=AsyncMock())
        self._stub_parent = parent_raw

    async def _fetch_parent_raw(self, node: Any) -> NodeSummaryRaw | None:
        return self._stub_parent


# ── compute_source_hash_for ──────────────────────────────────────


class TestComputeSourceHashForFormula:
    """``compute_source_hash_for`` derives the key from ``parent.enclosing_context``
    via the same pure helpers as the first-axis formulas. Acceptance #3.
    """

    async def test_deterministic_across_calls(self) -> None:
        parent = _make_raw(enclosing_context="course-level methodist context")
        child = _make_raw(course_node_id=uuid.uuid4())
        svc = _StubService(parent_raw=parent)
        first = await svc.compute_source_hash_for(child)
        second = await svc.compute_source_hash_for(child)
        assert first == second

    async def test_parent_context_change_flips_hash(self) -> None:
        # Acceptance #3 load-bearing assertion.
        a_parent = _make_raw(enclosing_context="version one")
        b_parent = _make_raw(enclosing_context="version two")
        child = _make_raw()
        a_hash = await _StubService(parent_raw=a_parent).compute_source_hash_for(child)
        b_hash = await _StubService(parent_raw=b_parent).compute_source_hash_for(child)
        assert a_hash != b_hash

    async def test_parent_context_none_and_empty_string_equivalent(self) -> None:
        # ``None``-coalesce to ``""`` mirrors the convention in
        # ``_node_summary_raw_payload`` — absent enclosing_context (parent
        # not yet generated by 3.2.3) hashes the same as explicit empty
        # string, so children get a deterministic "context-absent" key.
        none_parent = _make_raw(enclosing_context=None)
        empty_parent = _make_raw(enclosing_context="")
        child = _make_raw()
        none_hash = await _StubService(parent_raw=none_parent).compute_source_hash_for(
            child
        )
        empty_hash = await _StubService(
            parent_raw=empty_parent
        ).compute_source_hash_for(child)
        assert none_hash == empty_hash
        assert none_hash is not None  # absent → "" still yields a real hash

    async def test_hash_is_64_char_hex(self) -> None:
        parent = _make_raw(enclosing_context="something")
        child = _make_raw()
        digest = await _StubService(parent_raw=parent).compute_source_hash_for(child)
        assert digest is not None
        assert len(digest) == 64
        assert all(c in "0123456789abcdef" for c in digest)


